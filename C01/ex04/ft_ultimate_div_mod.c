void	ft_ultimate_div_mod(int *a, int *b)
{
	int	temp;

	if (b == 0)
	{
		*a = 0;
		*b = 0;
		return ;
	}
	temp = *a / *b;
	*b = *a % *b;
	*a = temp;
}
